const fs = require('fs');
const path = require('path');

const writeLegalPage = (file, title, htmlContent) => {
    const fullPath = path.join(__dirname, file, 'index.html');
    if (!fs.existsSync(fullPath)) return;
    let content = fs.readFileSync(fullPath, 'utf-8');
    
    // Replace everything inside <main class="page-main"> ... </main>
    const newMain = `
  <main class="page-main">
    <div class="fade-in">
      <h1 class="page-title">${title}</h1>
      <div class="page-underline"></div>
      <div class="legal-card" style="padding: 2rem; line-height: 1.8;">
${htmlContent}
      </div>
    </div>
  </main>`;
    
    content = content.replace(/<main class="page-main">[\s\S]*?<\/main>/, newMain);
    fs.writeFileSync(fullPath, content);
    console.log(`Updated ${file}/index.html`);
};

